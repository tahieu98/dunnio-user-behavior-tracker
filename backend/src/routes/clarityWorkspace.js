'use strict';
const express=require('express');
const {authenticate,authorize}=require('../middleware/auth');
const {asyncHandler}=require('../middleware/errorHandler');
const store=require('../services/clarityWorkspace');
const router=express.Router();
router.use(authenticate);
const write=authorize('admin','dev');
const ok=fn=>asyncHandler(async(req,res)=>res.json({success:true,data:await fn(req)}));
router.get('/catalog',ok(()=>store.catalog()));
router.get('/reports',ok(req=>store.list(req.query)));
router.post('/reports',write,ok(req=>store.save(req.body,req.user.id)));
router.get('/reports/:id',ok(req=>store.get(req.params.id)));
router.patch('/reports/:id/anchors',write,ok(req=>store.anchors(req.params.id,req.body)));
router.post('/compare',ok(req=>store.compare(req.body)));
router.get('/runs',ok(req=>store.runs(req.query.siteId)));
router.post('/runs',write,ok(req=>store.createRun(req.body,req.user.id)));
router.get('/runs/:id',ok(req=>store.run(req.params.id)));
router.patch('/jobs/:id',write,ok(req=>store.job(req.params.id,req.body)));
module.exports=router;
