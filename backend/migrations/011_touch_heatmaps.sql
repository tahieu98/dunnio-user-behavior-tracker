 viewport_width INT UNSIGNED NOT NULL,
 viewport_height INT UNSIGNED NOT NULL,
 document_height INT UNSIGNED NOT NULL,
 sample_rate DECIMAL(8,6) NOT NULL,
 x_bucket INT UNSIGNED NOT NULL,
 y_bucket INT UNSIGNED NOT NULL,
 grid_col TINYINT UNSIGNED NOT NULL,
 grid_row INT UNSIGNED NOT NULL,
 element_key VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 region_key VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 anchor_quality VARCHAR(12) CHARACTER SET ascii NOT NULL,
 fixed BOOLEAN NOT NULL,
 pointer_type VARCHAR(12) CHARACTER SET ascii NOT NULL,
 count BIGINT UNSIGNED NOT NULL DEFAULT 0,
 PRIMARY KEY(site_id,event_date,dimension_hash),
 INDEX idx_touch_point_report(site_id,page_path,device,layout_version,viewport_width,event_date),
 FOREIGN KEY(site_id) REFERENCES tracking_sites(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
