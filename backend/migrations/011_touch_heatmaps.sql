-- Receipts are retained for at least 72 hours. Counters never contain visitor identifiers.
CREATE TABLE IF NOT EXISTS touch_batches (
 site_id INT NOT NULL,
 batch_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 payload_sha256 CHAR(64) CHARACTER SET ascii NOT NULL,
 claim_token CHAR(36) CHARACTER SET ascii NOT NULL,
 sample_rate DECIMAL(8,6) NOT NULL,
 entry_count INT UNSIGNED NOT NULL,
 pageviews BIGINT UNSIGNED NOT NULL DEFAULT 0,
 taps BIGINT UNSIGNED NOT NULL DEFAULT 0,
 received_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
 PRIMARY KEY(site_id,batch_id),
 INDEX idx_touch_receipt_time(received_at),
 FOREIGN KEY(site_id) REFERENCES tracking_sites(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS touch_daily_pages (
 site_id INT NOT NULL,
 event_date DATE NOT NULL,
 dimension_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 page_path VARCHAR(255) NOT NULL,
 device VARCHAR(12) CHARACTER SET ascii NOT NULL,
 layout_version VARCHAR(80) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 viewport_width INT UNSIGNED NOT NULL,
 viewport_height INT UNSIGNED NOT NULL,
 document_height INT UNSIGNED NOT NULL,
 sample_rate DECIMAL(8,6) NOT NULL,
 pageviews BIGINT UNSIGNED NOT NULL DEFAULT 0,
 taps BIGINT UNSIGNED NOT NULL DEFAULT 0,
 first_seen DATETIME(3) NOT NULL,
 last_seen DATETIME(3) NOT NULL,
 PRIMARY KEY(site_id,event_date,dimension_hash),
 INDEX idx_touch_page_report(site_id,page_path,device,layout_version,viewport_width,event_date),
 FOREIGN KEY(site_id) REFERENCES tracking_sites(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS touch_daily_points (
 site_id INT NOT NULL,
 event_date DATE NOT NULL,
 dimension_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 page_path VARCHAR(255) NOT NULL,
 device VARCHAR(12) CHARACTER SET ascii NOT NULL,
